for species_list in db.values():
    for species in species_list:
        clean_name = species.replace('_', ' ')
        clean_to_orig[clean_name] = species

clade_results = defaultdict(lambda: defaultdict(list))
phlist_global = []   # every (major, minor) pair from the WHOLE original dataset
total_global = 0

if os.path.exists(file_path):
    with open(file_path, "r", encoding="utf-8") as f:
        reader = csv.reader(f)
        next(reader, None)
        for row in reader:
            total_global += 1
            taxon = row[0]
            major_clade = row[7]
            minor_clade = row[8]
            phlist_global.append((major_clade, minor_clade))

            if taxon in clean_to_orig:
                orig_species_name = clean_to_orig[taxon]
                clade_pair = [major_clade, minor_clade]
                for gene_family, species_list in db.items():
                    if orig_species_name in species_list:
                        if clade_pair not in clade_results[gene_family][orig_species_name]:
                            clade_results[gene_family][orig_species_name].append(clade_pair)

# Global percentage lookup (out of WHOLE original dataset)
pair_counts_global = Counter(phlist_global)
Percentage_global = {
    pair: (count / total_global) * 100
    for pair, count in pair_counts_global.items()
}

# Write one output file per gene family, with BOTH percentages
for gene_family, species_dict in clade_results.items():
    output_tsv = f"{gene_family}_clade_results.tsv"

    # Collect all clade pairs for THIS gene family only
    pairs_this_family = []
    for orig_species_name, clade_pairs in species_dict.items():
        for clade_pair in clade_pairs:
            pairs_this_family.append((clade_pair[0], clade_pair[1]))

    total_this_family = len(pairs_this_family)
    pair_counts_this_family = Counter(pairs_this_family)
    Percentage_this_family = {
        pair: (count / total_this_family) * 100
        for pair, count in pair_counts_this_family.items()
    }

    # Build table rows with both percentages
    table_data = []
    for orig_species_name, clade_pairs in species_dict.items():
        for clade_pair in clade_pairs:
            pair_key = (clade_pair[0], clade_pair[1])
            pct_family = Percentage_this_family.get(pair_key, 0)
            pct_global = Percentage_global.get(pair_key, 0)
            table_data.append({
                "Taxon": orig_species_name.split("_")[0],
                "Major_Clade": clade_pair[0],
                "Minor_Clade": clade_pair[1],
                "Percentage_in_Family": round(pct_family, 2),
                "Percentage_in_Dataset": round(pct_global, 2),
           
            })

    with open(output_tsv, "w", newline="", encoding="utf-8") as f:
        fieldnames = ["Taxon", "Major_Clade", "Minor_Clade", "Percentage_in_Family", "Percentage_in_Dataset"]
        writer = csv.DictWriter(f, fieldnames=fieldnames, delimiter="\t")
        writer.writeheader()
        writer.writerows(table_data)
